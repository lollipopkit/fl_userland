#!/usr/bin/env python3
"""Report `#[cfg(test)]` stubs standing in for a symbol nothing exports.

The complement of `tools/dup-stubs.py`. That one asks whether a test double has
a *second* definition in the same link; this one asks whether it has **any**
counterpart at all.

A stub is written because the crate under test reaches something by symbol. When
that call becomes a Rust call — which is what most of this migration has been —
the `#[no_mangle]` on the real function comes off, and the stub is left behind
defining a symbol nobody references. It links, it never runs, and it says in the
source that the test substitutes something it does not.

**50 of 65 on 2026-09-09**, from `native_offload_forward_signal` (whose export
had gone the same day) to a `mem_ptr` and a `mounts_lock` that stopped being
exports earlier in the month. Nothing had looked, because the failure is
completely silent: a stub for a symbol that does not exist is not an error at
any stage. Five more were generated by a `stub!` macro in `crates/fs/ttydev` and
so invisible to this scan; deleting that macro is what left the blind spot with
no instances.

**The blind spot filled up again, and it is closed now** (2026-09-30).
`crates/fs/proc`'s test module grew three such macros -- `zero!`, `zero_arg!`
and `null_arg!` -- and nine of the doubles they generated stood in for symbols
nothing exported: `fdtable_size` and `fdtable_snapshot_numbers`, which had
become methods, and seven more. The scan read `macro_rules!` for none of it and
answered "every test double stands in for a symbol that exists". It expands the
one shape used here now -- a `macro_rules!` whose body puts `#[no_mangle]` on a
`fn $name` or `static $name`, invoked with a comma-separated list whose items
each begin with the name -- in product code as well as tests, since a product
export made by a macro would otherwise read as missing.

## A double of a symbol that *does* exist is a defect too (2026-09-30)

The other half of the question, and the one `tools/dup-stubs.py` could not
answer: that tool reads the linker's duplicate-symbol warnings, and `ld` warns
only when both definitions are **loaded** -- an archive member is loaded for a
symbol something references. A double nothing references is never linked, and
neither is the real symbol, so the link is silent and the double says in the
source that the test substitutes something it does not. Seven were found at
once: `task_self` three times (`crates/fs/sockrestart`, whose test comment
relied on it answering non-null; `crates/kernel/mmapcalls`; and a whole crate,
`crates/kernel/taskview-teststub`, used by two others), `fd_close`, `tty_open`,
and `crates/fs/proc`'s `tmpfs` and `devptsfs`. None was linked.

A double that *is* referenced is the case `dup-stubs.py` does see, and it is a
second definition `ld` picks between -- also a defect, and the answer for both
is the one this tree settled on 2026-09-06: substitute with a `use` behind a
`cfg`, which has no symbol and checks the signature. So any `#[no_mangle]` in
test code that names a product export fails here.

## What it does not decide

A stub that *is* referenced but by something outside this workspace — an
embedder, or a C source — would read as dead here. There is no such case today:
`iul.h` is the whole interface and `tools/dead-exports.py` already models it. If
one appears, the answer is the same as that tool's, an ALLOWED entry with the
reason.

**Fails**, where `dup-stubs.py` reports. That one cannot decide: which of two
definitions `ld` picked is not something the source says, and a driven double is
a legitimate shape. Here the whole fact is in this repository — a symbol nothing
exports cannot be reached *through the symbol* by anything — so the answer is
mechanical. A stub a test calls by path (`c_stubs::foo()`) is the one shape that
is not a defect; `ALLOWED` is for that, with the reason.

## Two things this gets right that a first attempt would not

**It matches braces.** Cutting a file at its first `#[cfg(test)]` is wrong
whenever a crate's tests are not last, which is the defect
`docs/changelog/2026-09-06-a-gate-that-cut-every-file-at-its-first-test.md`
records in `tools/rust-c-abi.py`: `crates/kernel/pids` has a test module at
line 308 with thirteen exports after it.

**It asserts it found exports.** A gate covering nothing reads as a clean run.
It used to exit non-zero if there were no test doubles at all; since
2026-09-30 there are none, which is the state it exists to reach, so what it
asserts is that it found the product's `#[no_mangle]` exports to compare
against -- which is what would stop matching if the attribute were spelled
differently tomorrow.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Stubs a test calls by path rather than through the symbol, which the argument
# above does not cover. Name -> the reason. Empty since 2026-09-09, when the
# last fifty went; put one here rather than deleting a test's subject.
ALLOWED: dict[str, str] = {}

# `#[unsafe(no_mangle)]` (2024 edition) or the bare form, then any further
# attributes, then the definition. Macro-generated ones are invisible here and
# that is the same blind spot every source analysis in this tree has.
EXPORT = re.compile(
    r"#\[(?:unsafe\()?no_mangle\)?\]\s*(?:#\[[^\]]*\]\s*)*"
    r"(?:pub(?:\([^)]*\))? )?(?:unsafe )?extern \"C\" fn (\w+)"
)
# A `#[no_mangle] pub static`, which the same argument covers.
EXPORT_STATIC = re.compile(
    r"#\[(?:unsafe\()?no_mangle\)?\]\s*(?:#\[[^\]]*\]\s*)*"
    r"(?:pub(?:\([^)]*\))? )?static (?:mut )?(\w+)"
)


def match_brace(src, i):
    """The index of the bracket closing the one at `i`, skipping strings and
    comments; -1 if it is never closed."""
    opening = src[i]
    closing = {"{": "}", "(": ")", "[": "]"}[opening]
    depth, j, in_str, in_line, in_block = 0, i, False, False, False
    while j < len(src):
        c = src[j]
        nxt = src[j + 1] if j + 1 < len(src) else ""
        if in_line:
            if c == "\n":
                in_line = False
        elif in_block:
            if c == "*" and nxt == "/":
                in_block, j = False, j + 1
        elif in_str:
            if c == "\\":
                j += 1
            elif c == '"':
                in_str = False
        elif c == "/" and nxt == "/":
            in_line, j = True, j + 1
        elif c == "/" and nxt == "*":
            in_block, j = True, j + 1
        elif c == '"':
            in_str = True
        elif c == opening:
            depth += 1
        elif c == closing:
            depth -= 1
            if depth == 0:
                return j
        j += 1
    return -1


MACRO_DEF = re.compile(r"macro_rules!\s*(\w+)\s*\{")
MACRO_EXPORTS = re.compile(r"no_mangle[\s\S]*?(?:\bfn|\bstatic(?:\s+mut)?)\s+\$name\b")


def macro_exports(src):
    """(position, name) for every symbol a local `#[no_mangle]`-emitting
    `macro_rules!` is invoked to define. See the module comment."""
    emitting = set()
    for m in MACRO_DEF.finditer(src):
        end = match_brace(src, m.end() - 1)
        if end > 0 and MACRO_EXPORTS.search(src[m.end():end]):
            emitting.add(m.group(1))
    found = []
    for name in emitting:
        for m in re.finditer(r"(?<![\w$])" + re.escape(name) + r"!\s*([{(\[])", src):
            start = m.end() - 1
            end = match_brace(src, start)
            if end < 0:
                continue
            body, depth, item = src[start + 1:end], 0, ""
            items = []
            for c in body:
                if c in "([{":
                    depth += 1
                elif c in ")]}":
                    depth -= 1
                if c == "," and depth == 0:
                    items.append(item)
                    item = ""
                else:
                    item += c
            items.append(item)
            for it in items:
                ident = re.match(r"\s*(?://[^\n]*\n\s*)*(\w+)", it)
                if ident:
                    found.append((start, ident.group(1)))
    return found


def test_regions(src):
    """The [start, end) byte ranges of every `#[cfg(test)]` item, brace-matched.

    An item, not a module: a `#[cfg(test)]` on a single `fn` has no braces to
    match at the attribute, so the scan starts at the first `{` after it and
    ends at its partner. That covers `mod stubs { … }`, which is the shape
    every one of these is in.
    """
    spans = []
    for m in re.finditer(r"#\[cfg\(test\)\]", src):
        i = src.find("{", m.end())
        if i < 0:
            continue
        depth, j, in_str, in_chr, in_line, in_block = 0, i, False, False, False, False
        while j < len(src):
            c = src[j]
            nxt = src[j + 1] if j + 1 < len(src) else ""
            if in_line:
                if c == "\n":
                    in_line = False
            elif in_block:
                if c == "*" and nxt == "/":
                    in_block, j = False, j + 1
            elif in_str:
                if c == "\\":
                    j += 1
                elif c == '"':
                    in_str = False
            elif in_chr:
                if c == "\\":
                    j += 1
                elif c == "'":
                    in_chr = False
            elif c == "/" and nxt == "/":
                in_line, j = True, j + 1
            elif c == "/" and nxt == "*":
                in_block, j = True, j + 1
            elif c == '"':
                in_str = True
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    spans.append((i, j))
                    break
            j += 1
    return spans


def main():
    product, stubs = {}, {}
    for path in sorted((ROOT / "crates").rglob("*.rs")):
        src = path.read_text(errors="ignore")
        spans = test_regions(src)

        # A whole file of tests -- `mod tests;` behind a `#[cfg(test)]` in its
        # parent, or an integration test -- has no attribute inside it to find.
        rel = path.relative_to(ROOT).as_posix()
        whole = rel.endswith(("/tests.rs", "_tests.rs")) or "/tests/" in rel

        def in_test(pos):
            return whole or any(a <= pos < b for a, b in spans)

        found = [(m.start(), m.group(1)) for p in (EXPORT, EXPORT_STATIC) for m in p.finditer(src)]
        for pos, name in found + macro_exports(src):
            where = stubs if in_test(pos) else product
            where.setdefault(name, []).append(
                f"{path.relative_to(ROOT)}:{src[:pos].count(chr(10)) + 1}"
            )

    if not product:
        print("no product #[no_mangle] exports found at all, which is a scan")
        print("that stopped matching. This check asserts its own input; see the")
        print("module comment.")
        return 1

    dead = {
        k: v for k, v in sorted(stubs.items()) if k not in product and k not in ALLOWED
    }
    doubled = {k: v for k, v in sorted(stubs.items()) if k in product}
    print(f"{len(product)} #[no_mangle] names in product code, macro expansions included")
    print(f"{len(stubs)} #[no_mangle] test doubles across the workspace")
    print(f"{len(dead)} of them stand in for a symbol no product code exports")
    print(f"{len(doubled)} of them double a symbol product code does export")
    print(f"{len(ALLOWED)} in ALLOWED, called by path rather than through the symbol")

    if doubled:
        print()
        for name, places in doubled.items():
            print(f"  {name}  (exported at {product[name][0]})")
            for p in places:
                print(f"      {p}")
        print()
        print("Each is either never linked -- nothing references it, so it")
        print("substitutes nothing -- or a second definition `ld` picks between.")
        print("Delete it, or substitute with a `use` behind a `cfg`.")
        return 1

    if dead:
        print()
        for name, places in dead.items():
            print(f"  {name}")
            for p in places:
                print(f"      {p}")
        print()
        print("Each defines a symbol nothing references: it links, never runs,")
        print("and says the test substitutes something it does not. Delete it,")
        print("unless the test drives it -- see this file's header.")
        return 1

    print()
    print("No test double stands in for a symbol that is missing or live.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
