//! The gadget symbols the decoders emit addresses of.
//!
//! Every one is a `.gadget` label in
//! `asbestos/guest-arm64/gadgets-aarch64/*.S`. There is no C prototype and no
//! Rust definition to check them against, which is right: what a gadget has is
//! not a signature but a **code stream layout** — the words it reads after
//! itself — and that is written at each emission site, because that is where
//! getting it wrong shows up.
//!
//! Declared in one list rather than at the use sites, so that what the decoders
//! actually reach is visible, and so that the list shrinks as the rest of
//! `gen.c` moves.
//!
//! # One list, two things built from it
//!
//! The `gadgets!` macro emits the `extern` declarations and, under `cfg(test)`,
//! a definition of each name so that a test binary links — a standalone test
//! does not link the assembly, which is the reason several crates in this tree
//! had no tests at all. The stubs are `#[unsafe(no_mangle)]`, so the address a
//! decoder emits is the stub's, and "which gadget did it choose" becomes
//! something a test can assert rather than infer.
//!
//! They were two hand-written lists until the SIMD class arrived with 355 more
//! names. Two lists of 742 that have to agree, with nothing checking that they
//! do, is a drift waiting to happen: a name in one and not the other is either a
//! link error in the tests or a decoder that cannot see a gadget it needs.

use crate::Gadget;

/// Declare a gadget, and define a stand-in for it under `cfg(test)`.
macro_rules! gadgets {
    ($($name:ident,)*) => {
        unsafe extern "C" {
            $(pub fn $name();)*
        }

        #[cfg(test)]
        #[allow(dead_code)]
        mod stub {
            $(#[unsafe(no_mangle)] extern "C" fn $name() {})*
        }
    };
}

