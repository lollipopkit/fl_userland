//! The three `timerfd` syscalls and the descriptor they hand out.
//!
//! `crates/kernel/timerfd` has owned the expiration count and the flag and
//! clock rules for a while; `crates/util/timer` has owned the deadline queue
//! for longer. What was left in `kernel/time.c` was the code joining them —
//! the descriptor, its `fd_ops` table, the guest copies and the conversion
//! between the two representations of a deadline — which is what this is.
//!
//! # One object, one drop
//!
//! A timerfd descriptor is three things that have to be torn down in order: the
//! host timer, whose callback runs on the timer thread and touches the count,
//! and the count itself. Freeing the count first is a use-after-free of a
//! firing already in flight, and `timer_free` waits for one.
//!
//! The C kept them as three fields of `struct fd`'s union and did the ordering
//! by hand in `timerfd_close`. Here they are one `Box` whose `Drop` does it, so
//! there is one place that can be wrong rather than one per exit path — and
//! `sys_timerfd_create` gets that for free on the two failure paths where it
//! used to have to unwind by hand.
//!
//! # The two representations of a deadline
//!
//! The guest's `struct itimerspec_` puts the **interval first** and the value
//! second; the host's `struct timer_spec` is the other way round. Both are
//! generated by `build.rs` rather than written out, because that is a swap
//! neither compiler would catch.
//!
//! `TFD_TIMER_ABSTIME` is applied here rather than in either crate, because it
//! is the only part that needs to read a clock: an absolute deadline is made
//! relative against the *same* clock the timer runs on, which is why the
//! descriptor remembers which that is.

//! # `as i64` on a host `libc` field is not redundant
//!
//! `clippy::unnecessary_cast` reports the `time_t` and `suseconds_t` casts
//! here because those are already `i64` on this target. They are `i32` on a
//! 32-bit host, which this tree compiles on — `differential.sh` runs the
//! guest tests in a Linux container and the host tools build wherever they
//! are. The lint sees one target.
#![allow(clippy::unnecessary_cast)]

