/// A timerfd's driver: a read, a poll, a close and `TFD_IOC_SET_TICKS`.
///
/// A timerfd has no write and no seek, and leaving those to the trait's
/// defaults is what makes `f_get`'s callers answer the right errno.
struct TimerfdOps;

/// `TFD_IOC_SET_TICKS`, `_IOW('T', 0, u64)`: checkpoint/restore's way of
/// putting back an expiration count.
const TFD_IOC_SET_TICKS: u32 = 0x4008_5400;

static TIMERFD_FDOPS: TimerfdOps = TimerfdOps;

fn timerfd_fdops() -> Option<&'static dyn ffi::FdOps> {
    Some(&TIMERFD_FDOPS)
}

impl ffi::FdOps for TimerfdOps {
    fn caps(&self) -> ffi::Caps {
        ffi::Caps::READ_ONLY_STREAM
    }
    fn read(&self, fd: &ffi::fd, buf: &mut [u8]) -> isize {
        timerfd_read(fd, buf)
    }
    fn poll(&self, fd: &ffi::fd) -> Option<c_int> {
        Some(timerfd_poll(fd))
    }
    fn close(&self, fd: &mut ffi::fd) -> c_int {
        timerfd_close(fd)
    }
    /// Every other command is `ENOTTY`, as Linux's `timerfd_ioctl` answers.
    fn ioctl_size(&self, cmd: c_int) -> isize {
        if cmd as u32 == TFD_IOC_SET_TICKS { 8 } else { -1 }
    }
    /// `timerfd_show`: the clock, the expirations not yet read, the last
    /// `timerfd_settime`'s flags, and the time left and the interval, each
    /// as `(seconds, nanoseconds)`.
    fn show_fdinfo(&self, fd: &ffi::fd, out: &mut String) {
        let Some(this) = timerfd_of(fd) else {
            return;
        };
        let mut spec = util_timer::Spec::default();
        {
            let _guard = fs_fdobj::FdGuard::new(fd);
            util_timer::timer_get(this.timer, &mut spec);
        }
        let left = from_host(&spec);
        out.push_str(&format!(
            "clockid: {}\nticks: {}\nsettime flags: 0{:o}\nit_value: ({}, {})\nit_interval: ({}, {})\n",
            this.guest_clockid,
            this.state.ticks(),
            this.settime_flags.load(std::sync::atomic::Ordering::Relaxed),
            left.value.sec,
            left.value.nsec,
            left.interval.sec,
            left.interval.nsec,
        ));
    }
    /// The count is *replaced*, not added to, and readers and pollers are
    /// woken; zero is `EINVAL`. Linux's `ECANCELED` for a cancelled
    /// `TFD_TIMER_CANCEL_ON_SET` timer cannot happen here: the realtime clock
    /// is never set (see `crates/kernel/timerfd`). Measured against 7.2 by
    /// `clock2_probe`; it was `ENOTTY` until 2026-11-11.
    fn ioctl(&self, fd: &ffi::fd, _cmd: c_int, arg: ffi::IoctlArg<'_>) -> c_int {
        let (Some(this), Some(ticks)) = (timerfd_of(fd), arg.read::<u64>()) else {
            return Errno::EINVAL.as_c_int();
        };
        if ticks == 0 {
            return Errno::EINVAL.as_c_int();
        }
        this.state.set_ticks(ticks);
        0
    }
}

/// Everything a timerfd descriptor owns: `crates/kernel/timerfd`'s `Instance`.
use timerfd::Instance as TimerFd;

/// The descriptor's state, or `None` if this is not a timerfd.
///
/// A downcast of the state itself, which is what says whose description this
/// is. It was a downcast of the operations table followed by a read of a union
/// arm the table was trusted to imply.
fn timerfd_of(fd: &ffi::fd) -> Option<&TimerFd> {
    fd.driver_state::<TimerFd>()
}

fn timerfd_read(fd: &ffi::fd, buf: &mut [u8]) -> isize {
    if buf.len() < 8 {
        return guest_errno::isize_::EINVAL;
    }
    let Some(this) = timerfd_of(fd) else {
        return guest_errno::isize_::EINVAL;
    };
    let nonblock = fd.flags() & ffi::O_NONBLOCK_ != 0;
    let mut value: u64 = 0;
    let got = this.state.read_count(nonblock as i32, &mut value);
    if got < 0 {
        return got;
    }
    buf[..8].copy_from_slice(&value.to_ne_bytes());
    got
}

fn timerfd_poll(fd: &ffi::fd) -> c_int {
    timerfd_of(fd).map_or(0, |this| this.state.poll_types())
}

fn timerfd_close(fd: &mut ffi::fd) -> c_int {
    drop(fd.take_driver_state::<TimerFd>());
    0
}

