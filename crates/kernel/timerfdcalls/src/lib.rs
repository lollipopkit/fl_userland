/// The descriptor. `f_install` still answers a negative errno, which is what
/// `Errno::split` reads.
pub fn sys_timerfd_create(clockid: c_int, flags: c_int) -> Result<i64, Errno> {
    strace!("timerfd_create({clockid}, {flags:#x})");
    // Neither of these was checked. Any flag word produced a working
    // descriptor, so a program asking for TFD_NONBLOCK was told yes and then
    // hung on its first read; and every clock `clock_gettime` maps was
    // accepted, including the coarse and raw ones, which are readable but
    // cannot arm a timer -- that descriptor never became readable.
    //
    // The two alarm clocks are Linux's, and it wants `CAP_WAKE_ALARM` for
    // them after the flags and the clock are found valid. No guest has it --
    // waking the machine from suspend is the host's decision -- so they are
    // `EPERM`, as for a process without it, and as `clock_nanosleep` and
    // `timer_create` answer for the same clocks. They were `EINVAL` until
    // 2026-11-11, a "no such clock" a program cannot fall back on.
    if !timerfd::create_flags_valid(flags as u32) {
        return Err(Errno::EINVAL);
    }
    if matches!(clockid, timerfd::CLOCK_REALTIME_ALARM | timerfd::CLOCK_BOOTTIME_ALARM) {
        return Err(Errno::EPERM);
    }
    if !timerfd::clock_valid(clockid) {
        return Err(Errno::EINVAL);
    }
    let Some(host_clockid) = host_clock(clockid) else {
        return Err(Errno::EINVAL);
    };

    // Unpublished until `f_install` takes it, so a `return` below drops it
    // with nothing to close. There were **three** `fd_close` calls here once.
    let mut fd = fs_adhoc::adhoc_anon(timerfd_fdops(), Some(c"[timerfd]"));

    let state = timerfd::Descriptor::new(Arc::clone(&fd.poll_watchers));
    // The timer's target is the state, not the descriptor wrapper, so there is
    // no longer an ordering rule about boxing this before arming: the address
    // of `TimerFd` is nobody's business. Everything after this point unwinds by
    // dropping.
    // `state.clone()` rather than `Arc::clone(&state)`: the argument coerces
    // `Arc<Descriptor>` to `Arc<dyn Expire>`, and the associated-function form
    // makes inference try to resolve `Arc::clone` at the target type instead.
    let timer = util_timer::timer_new(host_clockid, state.clone());
    let this = Box::new(TimerFd {
        state,
        timer,
        clockid: host_clockid,
        guest_clockid: clockid,
        settime_flags: Default::default(),
    });
    if this.timer == TIMER_NONE {
        // Unchecked before, which left a descriptor whose timer could never be
        // armed: `timerfd_settime` answered an error the caller had no reason
        // to expect from a descriptor it had just been given.
        return Err(Errno::ENOMEM);
    }

    fd.set_driver_state(this);
    Errno::split(fs_fdobj::f_install(fd.into_owned(), flags) as i64)
}

pub fn sys_timerfd_settime(
    f: c_int,
    flags: c_int,
    new_value_addr: u64,
    old_value_addr: u64,
) -> Result<(), Errno> {
    strace!("timerfd_settime({f}, {flags}, {new_value_addr:#x}, {old_value_addr:#x})");

    // The new value is read **first**, before the flags and before the
    // descriptor: `timerfd_settime(-1, 0, NULL, NULL)` is `EFAULT` on a real
    // kernel and was `EBADF` here, which names the wrong argument. It is
    // `do_timerfd_settime`'s order and it is deliberate there -- the copy is
    // the one step that can fault, so it happens while nothing is held.
    let mem = GuestMem::current();
    let Ok(value) = mem.read_value::<ffi::itimerspec_>(new_value_addr) else {
        return Err(Errno::EFAULT);
    };

    // TFD_TIMER_CANCEL_ON_SET as well as TFD_TIMER_ABSTIME. This refused it,
    // where Linux takes it; see crates/kernel/timerfd for why accepting it is
    // the whole of implementing it here.
    if !timerfd::settime_flags_valid(flags as u32) {
        return Err(Errno::EINVAL);
    }
    let Some(fd) = fs_fdobj::f_get(f) else {
        return Err(Errno::EBADF);
    };
    let fd = &*fd;
    let Some(this) = timerfd_of(fd) else {
        return Err(Errno::EINVAL);
    };

    // Both halves, and the interval unconditionally -- Linux refuses a bad
    // interval even when the value is zero, which is the disarming case. The
    // interval is what every re-arm after the first uses, so an unchecked one
    // is a timer firing at a rate nobody asked for for the life of the process:
    // an interval of {-1, 0} armed a timer that expired continuously, and the
    // *next* test to use the descriptor saw its expiries.
    if !timeabi::itimerspec_valid(
        value.value.sec,
        value.value.nsec,
        value.interval.sec,
        value.interval.nsec,
    ) {
        return Err(Errno::EINVAL);
    }

    let mut spec = to_host(&value);
    // Expirations that have already happened by the time this returns: an
    // absolute deadline in the past. See `timerfd::overdue`.
    let mut due_now = 0;
    if flags as u32 & timerfd::TFD_TIMER_ABSTIME != 0 {
        let clockid = this.clockid;
        let armed = spec.value.sec != 0 || spec.value.nsec != 0;
        let (sec, nsec) = subtract((spec.value.sec, spec.value.nsec), now(clockid));
        let late_ns = -(i128::from(sec) * 1_000_000_000 + i128::from(nsec));
        if !armed {
            // Zero is disarm, absolute or not. It was subtracted from now
            // like any deadline, came out negative, and *armed* the timer.
        } else if late_ns >= 0 {
            let interval_ns = u128::try_from(
                i128::from(spec.interval.sec) * 1_000_000_000 + i128::from(spec.interval.nsec),
            )
            .unwrap_or(0);
            let (count, next_ns) = timerfd::overdue(late_ns as u128, interval_ns);
            due_now = count;
            spec.value.sec = (next_ns / 1_000_000_000) as _;
            spec.value.nsec = (next_ns % 1_000_000_000) as _;
        } else {
            spec.value.sec = sec as _;
            spec.value.nsec = nsec as _;
        }
    }

    // Arming again throws away an expiry that has already happened. Nothing did
    // this, so an event loop that rescheduled a timer -- arm, miss the fire,
    // arm again for later -- was handed the old expiry the moment it read, and
    // acted on a deadline that had been replaced. `evfd_probe` measures it:
    // `EAGAIN` on a real kernel, a stale count of 1 here.
    //
    // **Before `timer_set`, not after**, and the first version had it after "so
    // that a `timer_set` which fails leaves the descriptor as it was". That
    // ordering has a window: between arming and clearing, the timer this call
    // just armed can *fire*, and then the clear throws away an expiry that
    // belongs to the new deadline rather than the old one. A reader blocked on
    // the descriptor then waits for ever.
    //
    // The window needs a preemption longer than the timer between two adjacent
    // lines, so it is not something a loop can be made to hit -- 400 rounds of
    // a one-millisecond timer with the wrong order do not reproduce it. It is a
    // defect by inspection rather than by measurement, and it is fixed on that
    // basis: clearing first has no window at all, because every fire after this
    // point belongs to the timer just armed. The cost is that a `timer_set`
    // which fails has already discarded the old count, and everything that can
    // make it fail is checked above.
    //
    // The `timerfd` guest test hung once in a loaded suite run on the day this
    // was written. This ordering is the only candidate anybody has, and it was
    // **not** shown to be the cause; see the changelog.
    this.state.rearm();

    let mut old_spec = util_timer::Spec::default();
    let timer = this.timer;
    let err = {
        let _guard = fs_fdobj::FdGuard::new(fd);
        util_timer::timer_set(timer, spec, Some(&mut old_spec))
    };
    if err < 0 {
        return Err(Errno::from_negative_or_eio(err));
    }
    this.settime_flags.store(flags as u32, std::sync::atomic::Ordering::Relaxed);
    // After the re-arm above, which discards the old count, and after
    // `timer_set`, which armed only what comes *after* now.
    if due_now > 0 {
        this.state.fire_n(due_now);
    }

    if old_value_addr != 0 {
        let old = from_host(&old_spec);
        if mem.write_value(old_value_addr, &old) != 0 {
            return Err(Errno::EFAULT);
        }
    }
    Ok(())
}

pub fn sys_timerfd_gettime(f: c_int, curr_value_addr: u64) -> Result<(), Errno> {
    strace!("timerfd_gettime({f}, {curr_value_addr:#x})");
    let Some(fd) = fs_fdobj::f_get(f) else {
        return Err(Errno::EBADF);
    };
    let fd = &*fd;
    let Some(this) = timerfd_of(fd) else {
        return Err(Errno::EINVAL);
    };

    // Through the interface: `timer_get` already reports nothing rather than a
    // negative remaining time for a timer that is not armed, which is the check
    // the C used to spell out by reaching into the struct.
    let mut spec = util_timer::Spec::default();
    let timer = this.timer;
    {
        let _guard = fs_fdobj::FdGuard::new(fd);
        util_timer::timer_get(timer, &mut spec);
    }

    let value = from_host(&spec);
    if GuestMem::current().write_value(curr_value_addr, &value) != 0 {
        return Err(Errno::EFAULT);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The guest struct is `{interval, value}` and the host one is
    /// `{value, interval}`. A swap here is a timer that fires once after the
    /// interval and then never again, or repeats at the one-shot delay — both
    /// of which look plausible from outside.
    #[test]
    fn the_two_deadline_representations_are_the_other_way_round() {
        let guest = ffi::itimerspec_ {
            interval: ffi::timespec_ { sec: 5, nsec: 6 },
            value: ffi::timespec_ { sec: 1, nsec: 2 },
        };
        let host = to_host(&guest);
        assert_eq!((host.value.sec, host.value.nsec), (1, 2));
        assert_eq!((host.interval.sec, host.interval.nsec), (5, 6));

        let back = from_host(&host);
        assert_eq!((back.value.sec, back.value.nsec), (1, 2));
        assert_eq!((back.interval.sec, back.interval.nsec), (5, 6));
    }

    /// An absolute deadline is made relative by subtracting the clock. The
    /// borrow is the part worth a test: without it a deadline 0.5 s away
    /// computes as one 0.5 s in the past when the current nanoseconds are the
    /// larger.
    #[test]
    fn subtracting_borrows_a_second() {
        assert_eq!(subtract((10, 500), (4, 200)), (6, 300));
        assert_eq!(subtract((10, 200), (4, 500)), (5, 999_999_700));
        assert_eq!(subtract((10, 0), (10, 0)), (0, 0));
        // Already past: a negative result, which `timer_set` treats as "now".
        assert_eq!(subtract((4, 0), (10, 0)), (-6, 0));
    }

    /// Which host clock each accepted clock id runs on. The two CPU-time clocks
    /// and everything unknown have no timer to arm — `clock_valid` refuses them
    /// first, and this is the second line of the same rule.
    #[test]
    fn every_clock_a_timerfd_accepts_has_a_host_clock() {
        for id in [
            timerfd::CLOCK_REALTIME,
            timerfd::CLOCK_MONOTONIC,
            timerfd::CLOCK_BOOTTIME,
        ] {
            assert!(timerfd::clock_valid(id), "clock {id}");
            assert!(host_clock(id).is_some(), "clock {id}");
        }
        assert_eq!(host_clock(2), None, "CLOCK_PROCESS_CPUTIME_ID");
        assert_eq!(host_clock(3), None, "CLOCK_THREAD_CPUTIME_ID");
        assert_eq!(host_clock(99), None);
    }

    /// `CLOCK_BOOTTIME` is accepted and runs on the host's monotonic clock,
    /// which does not count suspended time. Asserted rather than left implicit
    /// because it is the one accepted clock whose host answer is an
    /// approximation.
    #[test]
    fn boottime_is_answered_from_monotonic() {
        assert_eq!(
            host_clock(timerfd::CLOCK_BOOTTIME),
            host_clock(timerfd::CLOCK_MONOTONIC)
        );
    }
}
