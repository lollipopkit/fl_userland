//! Hand-checkable native bodies for known guest functions, so the
//! prebuilt-gadget path can be A/B tested against threaded code.
//!
//! `kernel/offload_tests/prebuilt/*.c` until 2026-09-08 — six files compiled
//! only under `-Doffload_test_prebuilt=true` and `link_whole`d, because they
//! self-register from a constructor and the product core has no test hook.
//!
//! # Why this is a cargo feature and not a second staticlib
//!
//! The same answer `crates/kernel/offloadtest` gives for the symbol-level
//! handlers: two Rust staticlibs in one link are two standard libraries, and
//! under the release profile's LTO their symbols are strong globals. An `rlib`
//! behind a cargo feature has none of that, and a default build compiles
//! nothing here.
//!
//! # What a spec_fn is
//!
//! Host code standing in for one guest function. The interpreter enters it with
//! the guest's `cpu_state` and TLB instead of executing the function's
//! instructions, and it must leave the CPU exactly as the guest's own code
//! would have — which is what "bit-identical" in
//! `tests/offload/prebuilt/run.sh` measures.
//!
//! Guest memory goes through the TLB rather than the host's address space, so a
//! spec_fn is fork- and copy-on-write-safe. A guest `bl` cannot be a host call:
//! the callee is still guest code, so [`call`] either finds a spec_fn for it or
//! hands it back to the interpreter through
//! `asbestos_dispatch::prebuilt_call`.
//!
//! # The addresses are not the fixture's to know
//!
//! Every one of these was generated against a particular binary and carries
//! that binary's addresses. `tests/offload/prebuilt/run.sh` **rebuilds** those
//! binaries with whatever compiler the Alpine image has, and on 2026-09-08
//! `mix` had moved from 0x400314 to 0x400374 — so nothing was registered where
//! the guest executed, and the bit-identical check passed because the prebuilt
//! path was never taken. The script reads the real addresses with `nm` and
//! passes them in; [`base`] is the bias for the ones inside a body.

#![deny(unsafe_op_in_unsafe_fn)]

use std::ffi::CStr;
use std::sync::atomic::{AtomicU64, Ordering};

pub use taskview::ffi::cpu_state as Cpu;

/// The TLB. Opaque here — only [`ld`] and [`st`] touch it, and they hand it
/// straight to `crates/emu/tlb`.
pub type Tlb = taskview::ffi::tlb;

/// One translated guest function, as the registry holds it.
///
/// **The registry's alias, not a second one.** This was
/// `unsafe extern "C" fn(*mut Cpu, *mut Tlb)` written out here until
/// 2026-09-12, against a registry alias that said `*mut c_void` twice — so
/// every registration went through
/// `transmute::<SpecFn, offloadprebuilt::SpecFn>`, which is the one conversion
/// that reports nothing if the two stop agreeing. `crates/asbestos/offloadprebuilt`
/// names `cpu_state` and `tlb` now; see its `SpecFn`.
pub use offloadprebuilt::SpecFn;

mod bbjit;
mod callbench;
// `spec`, not `gen`: the latter is a reserved keyword in edition 2024.
mod mixbench;
pub mod spec;
// Generated by `tools/prebuilt_gadget_gen`, registered by nothing: it is the
// check that the generator still works. See its module comment.
pub mod mixgen;
pub mod outergen;
mod twochars;

// Not for a caller -- nothing but the registry calls a spec_fn -- but so the
// tests can check one against what it is supposed to mean, and the generated
// one against the hand-written one.
pub use callbench::{inner, outer};
pub use mixbench::mix;
pub use twochars::two_chars;

/// A guest address from the environment, or `fallback`.
///
/// `run.sh` sets these from `nm` on the binary it just built. The literal is
/// what the fixture was generated against and is what a hand-run gets.
fn env_addr(name: &str, fallback: u64) -> u64 {
    match std::env::var(name) {
        Ok(v) => {
            let v = v.trim();
            let (radix, digits) = match v.strip_prefix("0x").or_else(|| v.strip_prefix("0X")) {
                Some(hex) => (16, hex),
                None => (10, v),
            };
            u64::from_str_radix(digits, radix).unwrap_or(fallback)
        }
        Err(_) => fallback,
    }
}

/// The bias between the addresses a fixture was translated against and the ones
/// the binary actually has, for the ones written *inside* a body.
///
/// `callbench` shifted by 0x60 on 2026-09-08 and every literal in `spec_outer`
/// was wrong by that much — including the target of its `bl`, so the nested
/// dispatch ran the guest at an address that is not `inner`.
static CALLBENCH_BASE: AtomicU64 = AtomicU64::new(0);

pub(crate) fn base() -> u64 {
    CALLBENCH_BASE.load(Ordering::Relaxed)
}

/// Eight bytes of guest memory at `addr`.
///
/// # Safety
/// `tlb` is the running guest's.
pub(crate) unsafe fn ld(tlb: *mut Tlb, addr: u64) -> u64 {
    let mut v = [0; 8];
    // SAFETY: the caller's contract.
    unsafe { emu_tlb::access::Tlb::new(tlb).read(addr, &mut v) };
    u64::from_ne_bytes(v)
}

/// # Safety
/// As [`ld`].
pub(crate) unsafe fn st(tlb: *mut Tlb, addr: u64, value: u64) {
    // SAFETY: the caller's contract.
    unsafe { emu_tlb::access::Tlb::new(tlb).write(addr, &value.to_ne_bytes()) };
}

/// A guest `bl`, with a one-entry inline cache per call site.
///
/// If the callee has a spec_fn of its own, call it directly and stay in host
/// code; otherwise hand it to the interpreter, which runs the callee as
/// threaded code and returns here when it reaches the sentinel.
///
/// The cache matters: `prebuilt_call` re-enters the dispatch loop — a read
/// lock, a frame, a block lookup and an unwind — **per guest call**, which is
/// more than a tight call loop can carry.
///
/// # Safety
/// `cpu` and `tlb` are the running guest's, and this is called from a spec_fn.
pub(crate) unsafe fn call(cache: &AtomicU64, cpu: *mut Cpu, tlb: *mut Tlb, target: u64) {
    if cache.load(Ordering::Relaxed) == target {
        // The cached target is still the one; look it up again rather than
        // caching the pointer, which would be a second thing to keep in step.
        if let Some(f) = offloadprebuilt::native_offload_prebuilt_lookup(target) {
            // SAFETY: the caller's contract.
            unsafe { f(cpu, tlb) };
            return;
        }
    }
    if let Some(f) = offloadprebuilt::native_offload_prebuilt_lookup(target) {
        cache.store(target, Ordering::Relaxed);
        // SAFETY: the caller's contract.
        unsafe { f(cpu, tlb) };
        return;
    }
    // SAFETY: the caller's contract.
    unsafe { asbestos_dispatch::prebuilt_call(cpu, tlb, target) };
}

/// How many fixtures `register` actually registered. Two of the four are
/// behind a load base from the environment, so the number is not a constant —
/// and a caller asking "did the fixtures link" wants the truth rather than the
/// count of `add` calls in the source.
static REGISTERED: AtomicU64 = AtomicU64::new(0);

fn add(binary: &CStr, symbol: &CStr, addr: u64, f: SpecFn) {
    REGISTERED.fetch_add(1, Ordering::Relaxed);
    // SAFETY: two NUL-terminated names that outlive the process, and a function
    // of the registry's shape -- which is a type check since 2026-09-12 rather
    // than a `transmute` into it.
    unsafe {
        offloadprebuilt::native_offload_add_prebuilt(binary.as_ptr(), symbol.as_ptr(), addr, Some(f))
    };
}

/// Register every fixture. A constructor, because the product core has no test
/// hook to call — the same mechanism `crates/kernel/offloadtest` uses.
extern "C" fn register() {
    // tests/offload/prebuilt/guest builds both non-PIE, so their symbols are at
    // fixed addresses -- but which addresses depends on the toolchain, and
    // `run.sh` reads them out of the binary it just built.
    add(
        c"mixbench",
        c"mix",
        env_addr("IUL_MIXBENCH_MIX", 0x223dc4),
        mixbench::mix,
    );

    let outer = env_addr("IUL_CALLBENCH_OUTER", callbench::OUTER_ANCHOR);
    CALLBENCH_BASE.store(
        outer.wrapping_sub(callbench::OUTER_ANCHOR),
        Ordering::Relaxed,
    );
    add(c"callbench", c"outer", outer, callbench::outer);
    // Registering `inner` as well is what lets `outer`'s `bl` take the
    // inline-cache path instead of round-tripping the interpreter, which is
    // 1.9x against 5.3x.
    add(
        c"callbench",
        c"inner",
        env_addr("IUL_CALLBENCH_INNER", callbench::INNER_ANCHOR),
        callbench::inner,
    );

    // The two PoCs are in PIE binaries, so their load base is a runtime value
    // and nothing is registered without it.
    if std::env::var_os("IUL_BBJIT_BASE").is_some() {
        let base = env_addr("IUL_BBJIT_BASE", 0);
        bbjit::set_fallthrough(base + 0x7d0);
        add(c"al2", c"bbjit_loop", base + 0x7b0, bbjit::loop_body);
    }
    if std::env::var_os("IUL_TWOCHARS_BASE").is_some() {
        let base = env_addr("IUL_TWOCHARS_BASE", 0);
        twochars::set_base(base);
        add(
            c"libpython3.12.so.1.0",
            c"_PyToken_TwoChars",
            base + 0x108780,
            twochars::two_chars,
        );
    }
}

#[used]
#[unsafe(link_section = "__DATA,__mod_init_func")]
static REGISTER_CTOR: extern "C" fn() = register;

/// `pub` so the linker keeps the object holding the constructor, which is what
/// `crates/iul` names it for — and it answers the real count, so calling it
/// says whether the constructor ran as well as whether the crate linked.
pub fn registered() -> usize {
    REGISTERED.load(Ordering::Relaxed) as usize
}
