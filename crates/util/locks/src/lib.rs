/// `IUL_LOCK_TRACE=1`, read once. `util/sync.c`'s `g_lock_slow_trace`.
///
/// Here rather than in [`mutex`] since 2026-09-16, because [`wrlock`] reports
/// a slow wait too now and a second copy of "which environment variable turns
/// this on" is the kind of thing that ends up answering differently.
#[cfg(iul_lock_slow_trace)]
pub(crate) fn slow_trace_on() -> bool {
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *ON.get_or_init(|| std::env::var_os("IUL_LOCK_TRACE").is_some())
}

#[cfg(test)]
mod tests {
    use crate::wrlock;

    /// The write lock records **its caller's** site, not its own.
    ///
    /// This test is in `lib.rs` rather than beside `wrlock.rs`'s code on
    /// purpose: `file!()` here is a third path, different both from the
    /// constant the record used to carry (`crates/util/wrlock/src/lib.rs`, a
    /// crate that does not exist) and from the module that does the recording.
    /// So the path assertion distinguishes them, and the line assertion catches
    /// the other half -- `line!()` evaluated inside `write_trylock` names one
    /// of two lines in the lock itself, whoever called it.
    ///
    /// Both were true until 2026-09-16 and neither could be observed, because
    /// nothing read the three fields.
    #[test]
    fn the_write_lock_records_its_callers_site() {
        let l = wrlock::wrlock_t::default();
        assert_eq!(wrlock::holder(&l), "nobody", "a fresh lock has no writer");

        let taken_at = line!() + 2;
        // SAFETY: this thread holds neither side of a lock only it can see.
        assert!(crate::write_trywrlock!(&l), "it is free");

        let held = wrlock::holder(&l);
        assert!(
            held.contains("crates/util/locks/src/lib.rs"),
            "names the caller's file, not the lock's: {held}"
        );
        assert!(
            held.contains(&format!(":{taken_at}")),
            "names the caller's line ({taken_at}), not one inside the lock: {held}"
        );

        // SAFETY: this thread holds the write side.
        unsafe { wrlock::write_unlock(&l) };
        assert_eq!(wrlock::holder(&l), "nobody", "releasing clears the record");
    }

    /// Readers and a writer keep making progress while the readers are sent
    /// `SIGUSR1` as fast as one thread can, which is what this emulator does to
    /// its guest threads.
    ///
    /// Against the `pthread_rwlock_t` this lock was until 2026-11-13 it wedges
    /// within a second, every run (5 of 5): the writer's `trywrlock` never
    /// succeeds again though the count reads 0, and a reader stays parked in
    /// `__psynch_rw_rdlock`. `thread_start_signal` hung that way. See
    /// `wrlock_t` in `crates/util/synctypes`.
    #[test]
    fn a_signal_storm_does_not_wedge_the_lock() {
        use std::sync::atomic::{AtomicBool, AtomicU64, Ordering::Relaxed};
        use std::sync::Arc;
        use std::time::{Duration, Instant};

        extern "C" fn nothing(_: libc::c_int) {}
        // No `SA_RESTART`, as the emulator's own handler: an interrupted wait
        // returns rather than resuming.
        // SAFETY: an empty handler, installed with a zeroed mask.
        unsafe {
            let mut sa: libc::sigaction = std::mem::zeroed();
            sa.sa_sigaction = nothing as extern "C" fn(libc::c_int) as usize;
            assert_eq!(libc::sigaction(libc::SIGUSR1, &sa, std::ptr::null_mut()), 0);
        }

        const READERS: usize = 4;
        let l = Arc::new(wrlock::wrlock_t::default());
        let stop = Arc::new(AtomicBool::new(false));
        let progress: Arc<[AtomicU64; READERS + 1]> = Arc::new(Default::default());

        let mut threads = Vec::new();
        for i in 0..READERS {
            let (l, stop, progress) = (l.clone(), stop.clone(), progress.clone());
            threads.push(std::thread::spawn(move || {
                while !stop.load(Relaxed) {
                    wrlock::read_lock(&l);
                    std::hint::spin_loop();
                    // SAFETY: taken on the line above.
                    unsafe { wrlock::read_unlock(&l) };
                    if progress[i].fetch_add(1, Relaxed) % 64 == 0 {
                        std::thread::sleep(Duration::from_micros(200));
                    }
                }
            }));
        }
        let writer = {
            let (l, stop, progress) = (l.clone(), stop.clone(), progress.clone());
            std::thread::spawn(move || {
                while !stop.load(Relaxed) {
                    crate::write_wrlock!(&l);
                    for _ in 0..2000 {
                        std::hint::spin_loop();
                    }
                    // SAFETY: taken on the line above.
                    unsafe { wrlock::write_unlock(&l) };
                    progress[READERS].fetch_add(1, Relaxed);
                }
            })
        };
        use std::os::unix::thread::JoinHandleExt;
        let targets: Vec<libc::pthread_t> = threads.iter().map(|t| t.as_pthread_t()).collect();
        let storm = {
            let stop = stop.clone();
            std::thread::spawn(move || {
                while !stop.load(Relaxed) {
                    for &t in &targets {
                        // SAFETY: the readers are joined only after this
                        // thread is, so each id is a live thread's.
                        unsafe { libc::pthread_kill(t, libc::SIGUSR1) };
                    }
                }
            })
        };

        // Each window of half a second, every thread has to have moved. The
        // writer's deferral holds a reader off for at most 20 ms.
        let mut last: Vec<u64> = progress.iter().map(|p| p.load(Relaxed)).collect();
        let mut stalled = None;
        let end = Instant::now() + Duration::from_secs(3);
        while Instant::now() < end {
            std::thread::sleep(Duration::from_millis(500));
            let now: Vec<u64> = progress.iter().map(|p| p.load(Relaxed)).collect();
            if let Some(i) = (0..now.len()).find(|&i| now[i] == last[i]) {
                stalled = Some(i);
                break;
            }
            last = now;
        }
        if let Some(i) = stalled {
            // The threads are wedged and cannot be joined: report and leave
            // them, the process ends with the test binary.
            panic!(
                "{} made no progress for 500 ms under SIGUSR1: {:?}",
                if i == READERS { "the writer".to_string() } else { format!("reader {i}") },
                l
            );
        }
        stop.store(true, Relaxed);
        storm.join().unwrap();
        writer.join().unwrap();
        for t in threads {
            t.join().unwrap();
        }
    }
}
