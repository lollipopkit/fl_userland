//! The tree's lock primitives, in Rust.
//!
//! Two kinds, and they are here for the same reason: each had exactly one
//! implementation in `util/sync.h` as a `static inline`, reached from Rust
//! through a shim in `util/sync.c`, and the argument for keeping them was that
//! a Rust copy would be a **second** copy of a rule that must have one. That is
//! an argument for moving every caller, which is what these modules are.
//!
//! - [`wrlock`] is the address-space reader-writer lock: the writer-preference
//!   spin and the bounded reader defer, with the two deadlocks they prevent
//!   written out. Moved 2026-09-06.
//! - [`mutex`] is `lock_t`, the plain mutex with owner tracking that everything
//!   else in the tree uses.
//!
//! # Where the types are
//!
//! `crates/util/synctypes`, as hand-written source. They were generated by
//! bindgen here until 2026-09-08 and lived in `crates/kernel/abi` until
//! 2026-09-09 — this file said "the types are still generated ... bindgen
//! regenerates it on every build" until 2026-09-16, eight lines above the
//! comment on `mod ffi` saying they had stopped being, which is what a stale
//! heading costs.
//!
//! `lock_t` and `wrlock_t` still **grow under `-DLOCK_DEBUG=1`**, and `struct
//! mem`, `struct inode_data`, `struct sighand`, `struct mmu` and `struct
//! asbestos` embed one — so the layout is still a contract, and it is asserted
//! under both settings where it is defined rather than regenerated per crate.
//! `build.rs` is what is left of the generator: it turns the `-D` into the
//! `cfg` that picks the layout.

#![deny(unsafe_op_in_unsafe_fn)]

#[allow(non_upper_case_globals, non_camel_case_types, dead_code)]
/// `lock_t`, `wrlock_t` and the bookkeeping `-DLOCK_DEBUG=1` adds to a lock.
///
/// Generated from `util/sync.h` until 2026-09-08, for one reason: `lock_t`
/// **changes size** with that flag, so a hand-written layout here would be
/// wrong in exactly the build that exists to catch layout mistakes. It is a
/// `#[cfg(iul_lock_debug)]` field on `crates/util/synctypes`' definition now
/// -- written once, asserted under both settings, and this crate reads it. It
/// was `crates/kernel/abi`'s until 2026-09-09, and moved because a layer-0
/// crate may not name a `kernel` one for a mutex.
mod ffi {
    pub use util_synctypes::*;
}

